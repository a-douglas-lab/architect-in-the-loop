"""Command line: python -m ruleunits <command>. Run from spikes/rule-units/."""
import argparse
import json
from pathlib import Path

import yaml

from . import SPIKE, evaluate, hookfiles
from .artefacts import load_dir
from .glossary import load_default
from .select import rules_file, select
from .translate import alias
from .units import build_index, load_all


def main(argv=None):
    p = argparse.ArgumentParser(prog="ruleunits")
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("index", help="write index.yaml from the units")
    n = sub.add_parser("neutral", help="make neutral copies of every fixture")
    n.add_argument("out", type=Path)
    r = sub.add_parser("rules-file", help="select units for a feature folder (alias translator) and write their text")
    r.add_argument("feature", type=Path)
    r.add_argument("out", type=Path)
    h = sub.add_parser("hook-files", help="write a neutral feature copy, settings and MCP config for the live hook run")
    h.add_argument("out", type=Path)
    h.add_argument("--fixture", default="f8")
    sub.add_parser("eval-deterministic", help="score the alias and BM25 translators")
    m = sub.add_parser("eval-model", help="score model runs")
    m.add_argument("kind", choices=["model", "baseline-titles"])
    m.add_argument("mapping", type=Path)
    m.add_argument("runs", type=Path, nargs="+")
    a = p.parse_args(argv)

    if a.cmd == "index":
        idx = build_index(load_all())
        (SPIKE / "index.yaml").write_text(
            "# Generated by `python -m ruleunits index`. Don't edit by hand.\n" + yaml.safe_dump(idx, sort_keys=False),
            encoding="utf-8", newline="\n")
        print(f"{len(idx)} units")
    elif a.cmd == "neutral":
        mapping = evaluate.neutral_copies(a.out)
        evaluate.write(mapping, a.out / "mapping.json")
        print(json.dumps(mapping, indent=2))
    elif a.cmd == "rules-file":
        units = load_all()
        terms = alias(load_dir(a.feature), load_default())
        names = select(units, terms, "analyze")
        a.out.write_text(rules_file(units, names), encoding="utf-8", newline="\n")
        print(json.dumps({"terms": terms, "units": names}))
    elif a.cmd == "hook-files":
        paths = hookfiles.write(a.out, a.fixture)
        print(json.dumps({k: str(v) for k, v in paths.items()}, indent=2))
    elif a.cmd == "eval-deterministic":
        for name in ("alias", "bm25"):
            res = evaluate.deterministic(name)
            again = evaluate.deterministic(name)
            res["identical_on_second_run"] = res["units"] == again["units"] and res["terms"] == again["terms"]
            evaluate.write(res, SPIKE / "runs" / "selection" / f"{name}.json")
            print(name, "terms", res["term_score"]["recall"], res["term_score"]["precision"],
                  "units", res["unit_score"]["recall"], res["unit_score"]["precision"],
                  "identical", res["identical_on_second_run"])
    elif a.cmd == "eval-model":
        mapping = json.loads(a.mapping.read_text(encoding="utf-8"))
        runs = [evaluate.model_run(path, mapping, a.kind) for path in a.runs]
        key = "terms" if a.kind == "model" else "adrs"
        summary = {"kind": a.kind, "runs": runs, "stability": evaluate.stability(runs, key),
                   "unit_stability": evaluate.stability(runs, "units")}
        evaluate.write(summary, SPIKE / "runs" / "selection" / f"{a.kind}-scored.json")
        for i, r in enumerate(runs, 1):
            ts = r.get("term_score")
            print(a.kind, f"run {i}",
                  "terms", (ts["recall"], ts["precision"]) if ts else "-",
                  "units", r["unit_score"]["recall"], r["unit_score"]["precision"])
        print("stability", summary["stability"], "unit stability", summary["unit_stability"])


if __name__ == "__main__":
    main()
